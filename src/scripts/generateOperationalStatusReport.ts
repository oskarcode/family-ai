// Node utilities read report files, resolve paths, and run prerequisite report commands.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";

// Input types define the narrow report snapshots consolidated into operational status.
type UploadTracking = {
  summary: {
    total_records: number;
    invalid_source: number;
    raw_transferred: number;
    raw_not_transferred: number;
    index_now_total: number;
    index_transferred: number;
    index_not_transferred: number;
  };
};

type IndexingStatus = {
  instance: { id: string; source: string | null; status: string };
  stats: {
    completed: number;
    error: number;
    queued: number;
    running: number;
    skipped: number;
    outdated: number;
    file_embed_errors: Record<string, number>;
  };
  expected_unique_index_keys: number;
  completion_percent: number;
  remaining_count: number;
};

type FailedMapping = {
  totals: {
    key_collisions: number;
    error: number;
  };
  file_embed_errors: Record<string, number>;
};

type SearchValidation = {
  summary: {
    total_queries: number;
    queries_with_results: number;
    top_category_match_count: number;
    avg_citation_coverage: number;
    avg_top3_score: number;
  };
};

type CliConfig = {
  instanceId: string;
  includeSearchSnapshot: boolean;
};

// Project-relative paths locate all generated migration status artifacts.
const WORKDIR = process.cwd();
const OUT_DIR = path.join(WORKDIR, "outputs", "migration");

/**
 * Input:
 * - Command-line arguments for the operational status script.
 * Output:
 * - The selected AI Search instance and search-snapshot preference.
 * What this function does:
 * - Applies CLI overrides to the report's default runtime configuration.
 */
function parseArgs(argv: string[]): CliConfig {
  const config: CliConfig = {
    instanceId: "family-ai-chat-v3",
    includeSearchSnapshot: true,
  };

  for (let i = 0; i < argv.length; i += 1) {
    const arg = argv[i];
    if (arg === "--instance" && argv[i + 1]) {
      config.instanceId = argv[++i];
      continue;
    }
    if (arg === "--no-search") {
      config.includeSearchSnapshot = false;
      continue;
    }
  }

  return config;
}

/**
 * Input:
 * - An executable command and its argument list.
 * Output:
 * - No return value; child-process output is inherited by the current process.
 * What this function does:
 * - Runs a prerequisite report command synchronously in the project workspace.
 */
function run(command: string, args: string[]): void {
  execFileSync(command, args, {
    cwd: WORKDIR,
    stdio: "inherit",
    env: process.env,
    maxBuffer: 8 * 1024 * 1024,
  });
}

/**
 * Input:
 * - A JSON file path and the value to use when the file is absent.
 * Output:
 * - The parsed JSON value or the supplied fallback.
 * What this function does:
 * - Loads generated report data while tolerating absent optional snapshots.
 */
function readJson<T>(filePath: string, fallback: T): T {
  if (!fs.existsSync(filePath)) return fallback;
  return JSON.parse(fs.readFileSync(filePath, "utf8")) as T;
}

/**
 * Input:
 * - CLI configuration plus prerequisite migration reports generated by child commands.
 * Output:
 * - Consolidated JSON and Markdown operational status reports.
 * What this function does:
 * - Orchestrates report generation and summarizes transfer, indexing, failure, and search state.
 */
function main(): void {
  const config = parseArgs(process.argv.slice(2));

  fs.mkdirSync(OUT_DIR, { recursive: true });

  // Refresh reports in dependency order so the consolidated snapshot uses current upstream evidence.
  run("npm", ["run", "report:upload-tracking"]);
  run("npm", ["run", "report:indexing-status", "--", "--instance", config.instanceId]);
  run("npm", ["run", "report:failed-file-mapping"]);
  if (config.includeSearchSnapshot) {
    run("npm", ["run", "report:search-validation", "--", "--instance", config.instanceId]);
  }

  const upload = readJson<UploadTracking>(path.join(OUT_DIR, "upload_tracking_report.json"), {
    summary: {
      total_records: 0,
      invalid_source: 0,
      raw_transferred: 0,
      raw_not_transferred: 0,
      index_now_total: 0,
      index_transferred: 0,
      index_not_transferred: 0,
    },
  });

  const indexing = readJson<IndexingStatus>(path.join(OUT_DIR, "indexing_status_report.json"), {
    instance: { id: config.instanceId, source: null, status: "unknown" },
    stats: { completed: 0, error: 0, queued: 0, running: 0, skipped: 0, outdated: 0, file_embed_errors: {} },
    expected_unique_index_keys: 0,
    completion_percent: 0,
    remaining_count: 0,
  });

  const failed = readJson<FailedMapping>(path.join(OUT_DIR, "failed_file_mapping_report.json"), {
    totals: { key_collisions: 0, error: 0 },
    file_embed_errors: {},
  });

  const search = readJson<SearchValidation | null>(path.join(OUT_DIR, "search_validation_report.json"), null);

  // Reconcile queue activity into the single next milestone presented to operators.
  const nextMilestone =
    indexing.stats.queued === 0 && indexing.stats.running === 0
      ? "Indexing complete. Next: run final wait-mode search validation and then start uploader API + D1 write path."
      : "Indexing in progress. Keep v3 as active instance and rerun ops status until queued/running reach zero.";

  const payload = {
    generated_at: new Date().toISOString(),
    active_instance: config.instanceId,
    upload,
    indexing,
    failed,
    search,
    next_milestone: nextMilestone,
  };

  const md = `# Family AI Operational Status\n\n- Generated at: ${payload.generated_at}\n- Active instance: \`${config.instanceId}\`\n\n## Transfer Stage\n\n- Raw transferred: **${upload.summary.raw_transferred}**\n- Raw not transferred: **${upload.summary.raw_not_transferred}**\n- Index-ready transferred: **${upload.summary.index_transferred}/${upload.summary.index_now_total}**\n\n## Indexing Stage\n\n- Instance status: **${indexing.instance.status}**\n- Source bucket: \`${indexing.instance.source ?? "n/a"}\`\n- Completion: **${indexing.completion_percent}%**\n- Completed: **${indexing.stats.completed}**\n- Error: **${indexing.stats.error}**\n- Queued: **${indexing.stats.queued}**\n- Running: **${indexing.stats.running}**\n\n## Error Focus\n\n- Key collisions: **${failed.totals.key_collisions}**\n- Index errors: **${failed.totals.error}**\n- Error breakdown: ${Object.entries(failed.file_embed_errors)
    .map(([k, v]) => `${k}:${v}`)
    .join(", ") || "none"}\n\n## Search Snapshot\n\n${search
    ? `- Queries with results: **${search.summary.queries_with_results}/${search.summary.total_queries}**\n- Top category match: **${search.summary.top_category_match_count}/${search.summary.total_queries}**\n- Avg citation coverage: **${(search.summary.avg_citation_coverage * 100).toFixed(1)}%**`
    : "- skipped"}\n\n## Next Milestone\n\n- ${nextMilestone}\n`;

  const jsonPath = path.join(OUT_DIR, "operational_status_report.json");
  const mdPath = path.join(OUT_DIR, "operational_status_report.md");
  fs.writeFileSync(jsonPath, JSON.stringify(payload, null, 2));
  fs.writeFileSync(mdPath, md);

  console.log("Operational status report generated:");
  console.log(`- ${jsonPath}`);
  console.log(`- ${mdPath}`);
}

main();
